package com.leveledworld.skill;

/**
 * Efeitos numéricos que os perks fornecem. Cada perk soma (ou toma o máximo de) valores nestes stats e o
 * código de jogo consulta o total via {@link PerkStats}. Flags usam 1 = ativo.
 */
public enum Stat {
    // ----- Uma Mão (espadas)
    SWORD_DAMAGE, SWORD_BLEED, SWORD_BLEED_STRONG, SWORD_COMBO, SWORD_CRIT, SWORD_CRIT_MULT(Agg.MAX),
    SWORD_EXECUTE, SWORD_STAMINA, SWORD_CHARGE, SWORD_RAGE, SWORD_POISON, SWORD_DISARM, SWORD_LIFESTEAL,
    SWORD_ATTACK_SPEED, SWORD_DOUBLE,
    // ----- Duas Mãos (machados, maça, tridente)
    HEAVY_DAMAGE, HEAVY_ARMOR_PEN(Agg.MAX), HEAVY_KNOCKBACK, HEAVY_CLEAVE, HEAVY_BLEED, HEAVY_BLEED_STRONG,
    HEAVY_KILL_STRENGTH, HEAVY_STAMINA, HEAVY_HIT_STAMINA, HEAVY_CRIT, HEAVY_CRIT_MULT(Agg.MAX), HEAVY_HOLD_ARMOR,
    TRIDENT_THROWN, HEAVY_KB_RES,
    // ----- Arquearia
    RANGED_DAMAGE, DRAW_SPEED, DOUBLE_SHOT, ARROW_FAN, ARROW_RECOVER(Agg.MAX), RANGED_VS_BEASTS, HEADSHOT, ARROW_SLOW,
    RANGED_ARMOR_PEN(Agg.MAX), CROSSBOW_DAMAGE, ARROW_VELOCITY, LONG_SHOT, RANGED_CRIT,
    // ----- Bloqueio
    BLOCK_STAMINA(Agg.MAX), BLOCK_REFLECT(Agg.MAX), BLOCK_KNOCKBACK, BLOCK_STUN, BLOCK_DEFLECT, SHIELD_ELEMENTAL,
    COUNTER(Agg.MAX), SHIELD_RECOVERY, BLOCK_KB_IMMUNE, SHIELD_DURABILITY, SHIELD_HOLD_ARMOR, BLOCK_RESISTANCE,
    BLOCK_LAST_STAND, BLOCK_PASSIVE,
    // ----- Armadura Pesada
    HEAVY_ARMOR_BONUS, HEAVY_SET_ARMOR, HEAVY_SET_KB, HEAVY_SET_DR, HEAVY_PROJ_DR, HEAVY_EXPLOSION_DR,
    HEAVY_DURABILITY, HEAVY_REPAIR, HEAVY_DEBUFF_RES, HEAVY_REFLECT, HEAVY_MELEE_DR, HEAVY_EXPLOSION_KB,
    HEAVY_LOW_HP_ARMOR, HEAVY_COLOSSUS,
    // ----- Armadura Leve
    LIGHT_ARMOR_BONUS, DODGE, LIGHT_SPEED, LIGHT_SET_ARMOR, LIGHT_STAMINA_REGEN, SNEAK_FALL_DR, DODGE_PROJECTILE,
    LIGHT_JUMP, DODGE_COUNTER, DODGE_STAMINA,
    // ----- Furtividade
    SNEAK_VISIBILITY, SNEAK_MELEE_MULT(Agg.MAX), SNEAK_SWORD_MULT(Agg.MAX), SNEAK_RANGED_MULT(Agg.MAX), SILENT,
    SNEAK_SPEED, VANISH, SNEAK_LOOT, EVASION, NO_ENDERMAN, SNEAK_POISON, SNEAK_PROJ_DR, SHADOW_INVIS, PHANTOM,
    // ----- Atletismo
    STAMINA_MAX, SPRINT_COST, SPRINT_SPEED, JUMP_COST, JUMP_BOOST, SAFE_FALL, SWIM_SPEED, SWIM_FREE, CLIMB_SPEED,
    STAMINA_REGEN, SECOND_WIND, TIRELESS,
    // ----- Compartilhados (somam entre skills)
    FALL_DR, OXYGEN,
    // ----- Mineração
    MINING_SPEED, ORE_DOUBLE, ORE_SENSE(Agg.MAX), STONE_SPEED, VEIN_MINE, PICK_DURABILITY, AUTO_SMELT, ORE_XP,
    GEM_FIND, CAVE_VISION, MINING_NO_HUNGER,
    // ----- Lenhador
    WOOD_SPEED, LOG_EXTRA, TREE_FELL, AUTO_REPLANT, LEAF_DROPS, GOLDEN_APPLE, AXE_DURABILITY, PLANKS_BONUS,
    AXE_COMBAT, CHOP_HASTE, MUSHROOM_LOGS, APPLE_HEAL, FELL_XP, FELL_FREE,
    // ----- Ferraria
    SMITH_DURABILITY, QUALITY_IRON, QUALITY_DIAMOND, QUALITY_NETHERITE, SMITH_ENCHANT(Agg.MAX),
    SMITH_ENCHANT_LEVEL(Agg.MAX), ANVIL_DISCOUNT, ANVIL_SAFE, CRAFT_REFUND, SMITH_WEAPON_DAMAGE, SMITH_ARMOR,
    RECYCLE, MIN_FINE, MASTERWORK,
    // ----- Agricultura
    HARVEST_EXTRA, BONEMEAL_SAVE, CROP_AURA(Agg.MAX), CROP_AURA_SPEED(Agg.MAX), RIGHT_CLICK_HARVEST, AREA_HARVEST,
    TWINS, BABY_GROWTH, MEAT_EXTRA, WOOL_EXTRA, FOOD_BONUS, FOOD_REGEN, FISHING_EXTRA, GOLDEN_HARVEST, FARM_MASTER;

    public enum Agg { SUM, MAX }

    public final Agg agg;

    Stat() {
        this(Agg.SUM);
    }

    Stat(Agg agg) {
        this.agg = agg;
    }
}
